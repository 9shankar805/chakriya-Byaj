  static const List<String> _npDigits = ['०','१','२','३','४','५','६','७','८','९'];

  static String toNepaliNum(int n) {
    return n.toString().split('').map((c) {
      final d = int.tryParse(c);
      return d != null ? _npDigits[d] : c;
    }).join();
  }

