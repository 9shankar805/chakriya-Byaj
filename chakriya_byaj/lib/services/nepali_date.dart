  static const int _bsStartYear = 2000;
  // BS 2000 Baisakh 1 = AD 1943 April 14
  // Use UTC to avoid any timezone/DST drift
  static final DateTime _adEpoch = DateTime.utc(1943, 4, 14);

  // ── Days in a BS month ────────────────────────────────────────────────────
  static int daysInMonth(int bsYear, int bsMonth) {
    final idx = bsYear - _bsStartYear;
    if (idx < 0 || idx >= _data.length) return 30;
    return _data[idx][bsMonth - 1];
  }

  // ── Days in a BS year ─────────────────────────────────────────────────────
  static int daysInYear(int bsYear) {
    final idx = bsYear - _bsStartYear;
    if (idx < 0 || idx >= _data.length) return 365;
    return _data[idx].fold(0, (a, b) => a + b);
  }

  // ── AD → BS ──────────────────────────────────────────────────────────────
  static NepaliDate fromAD(DateTime ad) {
    // Force UTC noon to avoid any DST / timezone edge cases
    final adUtc = DateTime.utc(ad.year, ad.month, ad.day, 12);
    int totalDays = adUtc.difference(_adEpoch).inDays;

    int bsYear = _bsStartYear;
    int bsMonth = 1;

    while (true) {
      final yDays = daysInYear(bsYear);
      if (totalDays < yDays) break;
      totalDays -= yDays;
      bsYear++;
    }
    while (true) {
      final mDays = daysInMonth(bsYear, bsMonth);
      if (totalDays < mDays) break;
      totalDays -= mDays;
      bsMonth++;
    }
    return NepaliDate(bsYear, bsMonth, totalDays + 1);
  }

  // ── BS → AD ──────────────────────────────────────────────────────────────
  static DateTime toAD(NepaliDate bs) {
    int days = 0;
    for (int y = _bsStartYear; y < bs.year; y++) {
      days += daysInYear(y);
    }
    for (int m = 1; m < bs.month; m++) {
      days += daysInMonth(bs.year, m);
    }
    days += bs.day - 1;
    final ad = _adEpoch.add(Duration(days: days));
    return DateTime(ad.year, ad.month, ad.day);
  }

  // ── Today in BS ──────────────────────────────────────────────────────────
  static NepaliDate today() {
    final now = DateTime.now();
    return fromAD(DateTime(now.year, now.month, now.day));
  }

  // ── Day of week for BS date (0=Sun, 1=Mon…6=Sat) ─────────────────────────
  static int weekday(NepaliDate bs) {
    final ad = toAD(bs);
    // DateTime weekday: 1=Mon…7=Sun, convert to 0=Sun
    return ad.weekday % 7;
  }

  // ── First weekday of a BS month ───────────────────────────────────────────
  static int firstWeekdayOfMonth(int bsYear, int bsMonth) {
    return weekday(NepaliDate(bsYear, bsMonth, 1));
  }

